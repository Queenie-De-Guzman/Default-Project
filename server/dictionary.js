export function lookupDefinition(word, savedVocabulary = [], exampleSentence = '') {
  const clean = String(word || '').replace(/^[^\p{L}\p{N}]+|[^\p{L}\p{N}]+$/gu, '').toLowerCase();
  if (!clean) return null;

  const saved = (Array.isArray(savedVocabulary) ? savedVocabulary : []).find((item) => {
    const value = String(item.word || item.term || item.text || '').toLowerCase();
    return value === clean || value.includes(clean);
  });
  const entry = DICTIONARY[clean];
  const savedExample = String(saved?.example || saved?.example_sentence || saved?.sentence || saved?.source_quote || exampleSentence || '').trim();

  // Prefer a real dictionary meaning for common words; keep the story sentence
  // as the example so the explanation remains connected to what the child read.
  if (entry) {
    return {
      word: clean,
      partOfSpeech: 'word',
      definition: entry[1],
      example: savedExample || entry[2] || ''
    };
  }
  if (saved) {
    return {
      word: saved.word || saved.term || clean,
      partOfSpeech: saved.part_of_speech || saved.pos || 'word',
      definition: String(saved.definition || saved.meaning || saved.explanation || '').trim(),
      example: savedExample
    };
  }
  return null;
}
